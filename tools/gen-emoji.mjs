// Writes src/components/icons/emojiData.ts from emojibase-data (devDependency).
// Run: node tools/gen-emoji.mjs
//
// Every fully-qualified emoji except the "component" group (skin-tone and hair
// swatches) and the loose regional indicator letters. Names and keywords in
// German and English, for the picker's search. Skin tones: the five uniform
// variants per emoji that has them (multi-person emoji have mixed variants too;
// those are left out).
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';

const require = createRequire(import.meta.url);
const de = require('emojibase-data/de/compact.json');
const en = require('emojibase-data/en/compact.json');
const { version } = require('emojibase-data/package.json');
const deBy = new Map(de.map(e => [e.hexcode, e]));

// Group number in emojibase → our key; 2 (components) is dropped.
const GROUP_KEYS = { 0: 'smileys', 1: 'people', 3: 'nature', 4: 'food', 5: 'travel', 6: 'activities', 7: 'objects', 8: 'symbols', 9: 'flags' };
const TONES = ['1F3FB', '1F3FC', '1F3FD', '1F3FE', '1F3FF'];

const uniformSkins = e => {
  if (!e.skins) return null;
  const out = TONES.map(tone => e.skins.find(s => {
    const used = s.hexcode.split('-').filter(h => TONES.includes(h));
    return used.length > 0 && used.every(h => h === tone);
  })?.unicode);
  return out.every(Boolean) ? out : null;
};

const rows = en
  .filter(e => e.group !== undefined && GROUP_KEYS[e.group])
  .sort((a, b) => a.order - b.order)
  .map(e => {
    const d = deBy.get(e.hexcode);
    const words = [...new Set([...(d?.tags ?? []), ...(e.tags ?? [])])].join(' ');
    const skins = uniformSkins(e);
    const row = [e.unicode, Object.keys(GROUP_KEYS).indexOf(String(e.group)), d?.label ?? e.label, e.label, words];
    if (skins) row.push(skins);
    return row;
  });

const src = `// GENERATED by tools/gen-emoji.mjs from emojibase-data ${version} — do not edit.
// Loaded lazily (see emojiSource.ts): ${rows.length} emoji.

/** [emoji, group index, German name, English name, keywords, uniform skin tones?] */
export type EmojiRow = [string, number, string, string, string, string[]?];

const EMOJI: EmojiRow[] = ${JSON.stringify(rows)};

export default EMOJI;
`;
writeFileSync(new URL('../src/components/icons/emojiData.ts', import.meta.url), src);
writeFileSync(new URL('../src/components/icons/emojiGroups.ts', import.meta.url),
`// GENERATED by tools/gen-emoji.mjs — do not edit.
/** Emoji picker groups, in the order of the group index in emojiData. */
export const EMOJI_GROUP_KEYS = ${JSON.stringify(Object.values(GROUP_KEYS))} as const;
export const EMOJI_COUNT = ${rows.length};
`);
console.log(rows.length, 'emoji,', rows.filter(r => r[5]).length, 'with skin tones');

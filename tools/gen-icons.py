"""Generates the M3-Expressive icon geometry.

Paths are COMPUTED, not typed. Hand-written bezier soup is the classic source of
subtly-wrong icons (a circle that is not round, terminals that do not match), and
it cannot be reviewed. Every glyph below is built from primitives — circles,
rounded rects, regular polygons, rings, arcs — on the 24x24 M3 grid.
"""
import math

def f(x):
    r = round(x, 2)
    return int(r) if r == int(r) else r

def circle(cx, cy, r):
    """Full circle as two arcs — usable inside a multi-part path."""
    return (f"M{f(cx-r)} {f(cy)}"
            f"a{f(r)} {f(r)} 0 1 0 {f(2*r)} 0"
            f"a{f(r)} {f(r)} 0 1 0 {f(-2*r)} 0Z")

def ring(cx, cy, ro, ri):
    """Circle with a hole. Needs fill-rule=evenodd; the inner circle is wound
    the same way, and evenodd makes the overlap a real hole rather than a fill."""
    return circle(cx, cy, ro) + circle(cx, cy, ri)

def rrect(x, y, w, h, r):
    r = min(r, w / 2, h / 2)
    return (f"M{f(x+r)} {f(y)}h{f(w-2*r)}a{f(r)} {f(r)} 0 0 1 {f(r)} {f(r)}"
            f"v{f(h-2*r)}a{f(r)} {f(r)} 0 0 1 {f(-r)} {f(r)}"
            f"h{f(-(w-2*r))}a{f(r)} {f(r)} 0 0 1 {f(-r)} {f(-r)}"
            f"v{f(-(h-2*r))}a{f(r)} {f(r)} 0 0 1 {f(r)} {f(-r)}Z")

def poly(pts):
    d = f"M{f(pts[0][0])} {f(pts[0][1])}"
    for x, y in pts[1:]:
        d += f"L{f(x)} {f(y)}"
    return d + "Z"

def star(cx, cy, n, ro, ri, rot=-90):
    pts = []
    for i in range(2 * n):
        a = math.radians(rot + i * 180.0 / n)
        r = ro if i % 2 == 0 else ri
        pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return poly(pts)

def ngon(cx, cy, n, r, rot=-90):
    return poly([(cx + r*math.cos(math.radians(rot + i*360.0/n)),
                  cy + r*math.sin(math.radians(rot + i*360.0/n))) for i in range(n)])

def bar(x, y, w, h, r=None):
    return rrect(x, y, w, h, r if r is not None else min(w, h) / 2)

def chevron(cx, cy, w, h, t, down=True):
    """A thick V, built as a closed polygon so it scales with the icon."""
    s = 1 if down else -1
    return poly([(cx - w, cy - s*h/2), (cx, cy + s*h/2), (cx + w, cy - s*h/2),
                 (cx + w, cy - s*h/2 + s*t*1.4), (cx, cy + s*h/2 + s*t*1.4),
                 (cx - w, cy - s*h/2 + s*t*1.4)])


# -*- coding: utf-8 -*-
"""Generates the player avatar icon data from the vendored game-icons.net SVGs.

Input:  tools/avatar-icons/manifest.tsv + tools/avatar-icons/svg/<name>.svg
Output: src/components/icons/avatarCatalog.ts  (groups + authors, eager)
        src/components/icons/avatarPaths.ts    (path data, loaded lazily)

Each original SVG holds a black 512x512 background square and one white path;
only the path is kept. The paths use the default nonzero fill rule — NOT the
evenodd rule of the app's own icon set.
"""
import csv, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'tools', 'avatar-icons')
OUT = os.path.join(ROOT, 'src', 'components', 'icons')

AUTHOR_NAMES = {
    'lorc': 'Lorc', 'delapouite': 'Delapouite', 'skoll': 'Skoll',
    'caro-asercion': 'Caro Asercion', 'cathelineau': 'Cathelineau', 'kier-heyl': 'Kier Heyl',
    'darkzaitzev': 'DarkZaitzev', 'carl-olsen': 'Carl Olsen', 'various-artists': 'Various artists',
    'faithtoken': 'Faithtoken', 'sbed': 'Sbed',
}

rows = list(csv.DictReader(open(os.path.join(SRC, 'manifest.tsv'), encoding='utf-8'), delimiter='\t'))
groups, authors, paths = {}, {}, {}
for r in rows:
    svg = open(os.path.join(SRC, 'svg', r['name'] + '.svg'), encoding='utf-8').read()
    ds = re.findall(r'<path[^>]*\sd="([^"]+)"', svg)
    ds = [d for d in ds if d.replace(' ', '') != 'M00h512v512H0z']
    if len(ds) != 1:
        sys.exit(f"{r['name']}: expected one path besides the background, found {len(ds)}")
    if r['author'] not in AUTHOR_NAMES:
        sys.exit(f"unknown author {r['author']} — add a display name")
    groups.setdefault(r['group'], []).append(r['name'])
    authors[r['name']] = r['author']
    paths[r['name']] = ds[0]

header = '// Generated by tools/gen-avatar-icons.py — do not edit by hand.\n'
with open(os.path.join(OUT, 'avatarCatalog.ts'), 'w', encoding='utf-8') as f:
    f.write(header)
    f.write('/** game-icons.net avatars, stored as `gi:<name>`. CC BY 3.0 by their authors. */\n')
    f.write('export const GAME_ICON_GROUPS: { key: string; names: string[] }[] = ')
    f.write(json.dumps([{'key': k, 'names': v} for k, v in groups.items()], indent=2))
    f.write(';\n\n/** Author slug per icon (the folder in github.com/game-icons/icons). */\n')
    f.write('export const GAME_ICON_AUTHORS: Record<string, string> = ' + json.dumps(authors, indent=2) + ';\n\n')
    f.write('/** Display names of the authors, for the credit line. */\n')
    used = sorted({a for a in authors.values()}, key=lambda a: -list(authors.values()).count(a))
    f.write('export const GAME_ICON_AUTHOR_NAMES: string[] = ' + json.dumps([AUTHOR_NAMES[a] for a in used]) + ';\n')
with open(os.path.join(OUT, 'avatarPaths.ts'), 'w', encoding='utf-8') as f:
    f.write(header)
    f.write('/** Path data (512x512, nonzero fill) of the game-icons.net avatars. Loaded lazily. */\n')
    f.write('const AVATAR_PATHS: Record<string, string> = ' + json.dumps(paths, indent=1) + ';\n\nexport default AVATAR_PATHS;\n')
print(f'{len(paths)} icons in {len(groups)} groups, {len(set(authors.values()))} authors')
